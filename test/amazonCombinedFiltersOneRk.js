'use strict';
const assert=require('assert'),fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const filters=require('../src/modules/amazon/shared/imageFilters');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
for (const ext of ['.psd','.psb','.png']) assert(filters.matchesExtension(ext,'psd_png'));
for (const ext of ['.jpg','.jpeg','.png']) assert(filters.matchesExtension(ext,'png_jpg'));
assert(!filters.matchesExtension('.psd','png_jpg'));
assert(filters.matchesExtension('.tiff','raster'));
assert(!filters.matchesExtension('.psb','raster'));
const app=read('src/modules/amazon/renderer/app.js');
const html=read('src/modules/amazon/renderer/index.html');
const batch=read('src/modules/amazon/renderer/batchWorkspace.js');
const backend=read('src/modules/amazon/main/register.js');
assert(app.includes('return (variant?.files || []).filter(file => file.selected);'),'All assigned files must survive filter changes');
assert(!app.includes('if (!matchesSourceTypeFilter(file)) file.selected = false;'));
assert(html.includes('value="psd_png"') && html.includes('value="psd_png_jpg"'));
assert(!html.includes('id="amazonChooseCreative"'));
assert(batch.includes('for (const filter of formatFilters.filters)'));
assert(backend.includes('rkPlainTargetId'));
assert(backend.includes('result.rkPlainEligibleCount = 1'));
console.log('PASS combined format filters, persistent assignments, no global Creative, one designated RK Plain ID');
