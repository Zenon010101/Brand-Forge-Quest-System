'use strict';
const assert=require('assert'), fs=require('fs'), path=require('path');
const root=path.resolve(__dirname,'..');
const load=p=>fs.readFileSync(path.join(root,p),'utf8');
const batch=load('src/modules/amazon/renderer/batchWorkspace.js');
const app=load('src/modules/amazon/renderer/app.js');
const html=load('src/modules/amazon/renderer/index.html');
const locator=load('src/modules/project-location/renderer/projectLink.js');
const backend=load('src/modules/amazon/main/register.js');
assert(html.includes('id="batchAssignMainBtn"'));
assert(batch.includes('setFirstPickAsMain') && batch.includes('"Set Main #1"'));
assert(batch.includes('mainPath: item.files[0] || ""'));
assert(app.includes('setFolderMain(variant, file)'));
assert(app.includes('mainPath: selectedFiles(variant)[0]?.path'));
assert(locator.includes('"rkplain"'), 'RK PLAIN must be a fourth project detector role');
assert(app.includes('project?.roles?.rkplain?.folderPath'), 'linked RK folder not loaded into Amazon extras');
assert(backend.includes('linkedProject?.roles?.rkplain?.folderPath'), 'backend must use verified linked RK folder');
assert(!backend.includes('item.role !== "shared"'), 'Shared IDs may be selected as the one RK target');
assert(backend.includes('items: [{ id: matching[0].variantId, jpg: matching[0].jpgs[0] }]'), 'RK Plain must stage only one target ID');
assert(backend.includes('matching.length !== 1'), 'Require an unambiguous successfully-generated target');
assert(app.includes('rkPlainTargetId: rkTargetIdEl.value.trim()'), 'User-selected RK ID must reach main process');
console.log('PASS Set Main #1 UI in both Amazon modes, linked RK Plain destination, RK Plain for one selected ID only.');
